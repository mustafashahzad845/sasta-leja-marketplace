/**
 * Generates Frontend/Pages/JS/env.js from the project .env file.
 *
 * Browsers cannot read .env files, so the API base URL is written into a
 * small script that the pages load before JS/api.js. This keeps the API
 * location defined in exactly one place (the root .env) for both the
 * backend and the frontend.
 *
 * Usage (from the Backend folder): npm run env:frontend
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(rootDir, "Frontend", "Pages", "JS", "env.js");
const FALLBACK_API_BASE_URL = "http://localhost:4000/api";

function readEnvFile(filePath) {
  const values = {};
  if (!fs.existsSync(filePath)) return values;

  const contents = fs.readFileSync(filePath, "utf8");
  for (const line of contents.split(/\r?\n/)) {
    const trimmedLine = line.trim();
    if (!trimmedLine || trimmedLine.startsWith("#")) continue;

    const separatorIndex = trimmedLine.indexOf("=");
    if (separatorIndex === -1) continue;

    const key = trimmedLine.slice(0, separatorIndex).trim();
    let value = trimmedLine.slice(separatorIndex + 1).trim();

    const isDoubleQuoted = value.startsWith('"') && value.endsWith('"');
    const isSingleQuoted = value.startsWith("'") && value.endsWith("'");
    if (isDoubleQuoted || isSingleQuoted) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }
  return values;
}

const sharedEnv = readEnvFile(path.join(rootDir, ".env"));
// Backend/.env is only a fallback so existing setups keep working.
const backendEnv = readEnvFile(path.join(rootDir, "Backend", ".env"));

const apiBaseUrl = (sharedEnv.API_BASE_URL || backendEnv.API_BASE_URL || FALLBACK_API_BASE_URL)
  .trim()
  .replace(/\/+$/, "");

const output = `/**
 * Generated by scripts/generate-frontend-env.mjs from the project .env file.
 * Do not edit this file manually.
 *
 * To change the API base URL, update API_BASE_URL in the root .env and run:
 *   npm run env:frontend   (inside the Backend folder)
 */
window.SASTA_API_BASE = ${JSON.stringify(apiBaseUrl)};
`;

fs.writeFileSync(outputPath, output, "utf8");
console.log(`Frontend API base URL set to ${apiBaseUrl}`);
console.log(`Written to ${outputPath}`);
